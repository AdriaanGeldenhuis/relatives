<div class="doc-body">
    <p class="doc-intro">This Privacy Policy explains how we collect, use, store, and protect your data when using the Relatives app ("the App"). This policy applies to the Relatives Android app and website.</p>
    <p class="highlight"><a href="/legal/delete-account.php">Request deletion of your Relatives account and its data</a></p>


    <h3>1. Information We Collect</h3>

    <h4>A. Account Information</h4>
    <ul>
        <li>Name</li>
        <li>Email</li>
        <li>Password hash</li>
        <li>Avatar color or image</li>
        <li>Family group ID</li>
    </ul>

    <h4>B. Content You Create</h4>
    <ul>
        <li>Notes (text or audio)</li>
        <li>Shopping lists & items</li>
        <li>Messages</li>
        <li>Calendar events</li>
        <li>Schedules</li>
        <li>Uploaded media (if applicable)</li>
    </ul>

    <h4>C. Location Data (Optional)</h4>
    <p>Relatives collects location for family location sharing after you enable sharing and grant location permission. On Android, this includes when the app is closed or not in use while sharing is active. If you grant background access, the app can recover sharing after Android stops it and respond to a family member’s refresh request.</p>
    <ul>
        <li>GPS coordinates</li>
        <li>Accuracy radius</li>
        <li>Time of the fix, movement, speed, altitude and heading when available</li>
    </ul>
    <p>Your family group can see shared positions and available history. When you ask for directions, the relevant coordinates are sent to a mapping provider (Mapbox or OSRM). Offline fixes may be held briefly on your device for delivery when your connection returns.</p>
    <p>Use Stop sharing in the Android map or the Location Tracking notification to stop this device. Use Location Sharing in <a href="/profile/privacy.php">Privacy &amp; Security</a> to hide your position and history from family members and block new uploads across your account.</p>

    <h4>D. Device Information</h4>
    <ul>
        <li>Browser type</li>
        <li>App version</li>
        <li>IP address</li>
        <li>Device model (app only)</li>
        <li>OS version</li>
        <li>Device or app identifiers, including push notification registration tokens when notifications are enabled</li>
    </ul>

    <h4>E. Cookies and Local Storage</h4>
    <p>Used for:</p>
    <ul>
        <li>Login sessions</li>
        <li>Preferences</li>
        <li>App performance</li>
    </ul>
    <p class="doc-link">🍪 Details in the <a href="/legal/?doc=cookies">Cookie Policy</a>.</p>

    <h4>F. Purchases and optional features</h4>
    <p>When you subscribe through an app store, Relatives receives purchase identifiers, the plan, subscription status and renewal or expiry information for verification and support. The store processes payment card information.</p>
    <p>When you send a voice message or record an audio note, the recording is stored with that content. Optional AI features use the text or transcript you submit and the context needed for the request. Voice requests may be stored with the resulting response.</p>

    <h3>2. Why We Collect Data</h3>
    <p>We use data to:</p>
    <ul>
        <li>Provide core app features</li>
        <li>Display shared family content</li>
        <li>Maintain user sessions</li>
        <li>Improve app performance</li>
        <li>Deliver notifications and reminders</li>
        <li>Provide accurate map tracking (if enabled)</li>
        <li>Display weather information</li>
    </ul>

    <p class="highlight"><strong>We do NOT:</strong></p>
    <ul>
        <li>Sell your data</li>
        <li>Share your data for advertising</li>
        <li>Track you for marketing purposes</li>
    </ul>

    <h3>3. Sharing of Data</h3>
    <p>We share data ONLY:</p>
    <ul>
        <li>Within your family group (content you post, location if enabled)</li>
        <li>With service providers who support the app:
            <ul>
                <li>Hosting providers store account data and family content so Relatives can run.</li>
                <li>Our email delivery provider receives the email address and message needed to deliver account emails, such as password resets.</li>
                <li>OpenWeather receives the location or search term needed to return weather or place results.</li>
                <li>Mapbox or OSRM receives the coordinates needed for directions.</li>
                <li>Firebase Cloud Messaging receives device registration tokens and the notification payload to deliver push notifications.</li>
                <li>Google Play or the applicable store for subscriptions and purchase verification</li>
                <li>OpenAI when you use an AI feature, such as voice chat, to process the text or transcript you submit and the context needed for that response</li>
            </ul>
        </li>
    </ul>
    <p class="highlight">We do not provide your data to third parties for any other purpose.</p>

    <h3>4. Data Storage & Security</h3>
    <p>We use:</p>
    <ul>
        <li>One-way password hashes</li>
        <li>Secure HTTPS connections</li>
        <li>Database protections</li>

    </ul>
    <p>No system is 100% secure, but we take reasonable measures to protect your information.</p>

    <h3>5. Data Retention</h3>
    <p>We keep account data while your account is active and family content while it is needed to provide the family workspace. Family location history follows the family tracking history setting, which defaults to 30 days.</p>
    <p>You can request deletion through Profile → Delete account or the <a href="/legal/delete-account.php">web deletion page</a>. The privacy team verifies and processes requests for the account and its associated personal data, including location history. You can check whether a request is pending on the web page.</p>
    <p>We retain limited records only where needed for legal, billing, security or fraud-prevention purposes. The privacy team can explain what needs to be retained and why.</p>

    <h3>6. Your Rights</h3>
    <p>You may:</p>
    <ul>
        <li>Request access to your data</li>
        <li>Request correction of inaccurate data</li>
        <li><a href="/legal/delete-account.php">Request deletion of your account and associated personal data</a></li>
        <li>Withdraw location permission at any time</li>
    </ul>

    <h3>7. Children's Privacy</h3>
    <p>Location sharing is under the control of each user on their own device. Parents and guardians are responsible for deciding whether family members in their care should use Relatives.</p>

    <h3>8. Contact</h3>
    <p>For privacy concerns: <a href="mailto:privacy@relatives.co.za">privacy@relatives.co.za</a></p>
